# variable = value
my_int = 5      # int: whole number, no decimal point
my_float = 5.5  # float: number with a decimal point

print(my_int)
print(my_float)

# Dividing two ints with / always gives a float
division = 10 / 5
print(division)  # 2.0

# Floor division // divides, then rounds DOWN to the nearest integer
print(8 // 3)   # 2 (rounded down from 2.666)
print(-7 // 3)  # -3 (rounded down from -2.333, down means more negative)
